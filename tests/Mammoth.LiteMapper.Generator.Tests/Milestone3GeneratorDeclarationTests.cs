        [TestMethod]
        public void ConfigurationDiagnosticsAreReported()
        {
            AssertDiagnostic("LITEMAPPER0013", "[LiteMapper][LiteMapper] public static partial class Mapper { }");
            AssertDiagnostic("LITEMAPPER0008", "[LiteMapper(NameMatching = (NameMatching)999)] public static partial class Mapper { }");
            AssertDiagnostic("LITEMAPPER0009", "[LiteMapper] public static partial class Mapper { [MappingOptions(NameMatching = (NameMatching)999)] public static partial Target Map(Source source); } public sealed class Source { } public sealed class Target { }");
            AssertDiagnostic("LITEMAPPER0010", "[assembly: UseMapper(typeof(EmptyExternalMapper))] public static class EmptyExternalMapper { }");
            AssertDiagnostic("LITEMAPPER0011", "public sealed class ExternalMapper { public static Target Map(Source source) => new Target(); } [UseMapper(typeof(ExternalMapper))][LiteMapper] public static partial class Mapper { } public sealed class Source { } public sealed class Target { }");
