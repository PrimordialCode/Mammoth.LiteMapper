            AssertDiagnostic("LITEMAPPER0001", "[LiteMapper] public class Mapper { }");
            AssertDiagnostic("LITEMAPPER0002", "[LiteMapper] public partial struct Mapper { }");
            AssertDiagnostic("LITEMAPPER0003", "[LiteMapper] public partial class Mapper<T> { }");
            AssertDiagnostic("LITEMAPPER0004", "[LiteMapper] public abstract partial class Mapper { }");
            AssertDiagnostic("LITEMAPPER0001", "public class Outer { [LiteMapper] public partial class Mapper { } }");
        }

        [TestMethod]
