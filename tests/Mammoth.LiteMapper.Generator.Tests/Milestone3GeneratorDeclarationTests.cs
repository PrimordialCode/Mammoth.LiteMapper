    [TestClass]
    public sealed class Milestone3GeneratorDeclarationTests
    {
        [TestMethod]
        public void GeneratorImplementsIncrementalGeneratorOnly()
        {
            var generatorType = typeof(Mammoth.LiteMapper.Generator.LiteMapperGenerator);

            Assert.IsTrue(typeof(IIncrementalGenerator).IsAssignableFrom(generatorType));
            Assert.IsFalse(typeof(ISourceGenerator).IsAssignableFrom(generatorType));
            Assert.AreEqual(0, generatorType.GetFields(System.Reflection.BindingFlags.Instance | System.Reflection.BindingFlags.Public | System.Reflection.BindingFlags.NonPublic).Length);
        }

        [TestMethod]
        public void ValidStaticAndInstanceMappersProduceDeterministicDeclarationSources()
        {
            var result = RunGenerator(@"
using Mammoth.LiteMapper;

[LiteMapper]
public static partial class StaticMapper
{
    public static partial Target ToTarget(Source source);
}

[LiteMapper]
internal sealed partial class InstanceMapper
{
    internal partial Target ToTarget(Source source);
}

public sealed class Source { }
public sealed class Target { }
");

            AssertNoLiteMapperDiagnostics(result);
            Assert.AreEqual(2, result.GeneratedTrees.Length);
            CollectionAssert.AreEqual(
                result.GeneratedTrees.Select(t => t.FilePath).OrderBy(static p => p, StringComparer.Ordinal).ToArray(),
                result.GeneratedTrees.Select(t => t.FilePath).ToArray());
            StringAssert.Contains(result.GeneratedTrees[0].GetText().ToString(), "// <auto-generated/>");
            StringAssert.Contains(result.GeneratedTrees[0].GetText().ToString(), "partial class InstanceMapper");
            StringAssert.Contains(result.GeneratedTrees[1].GetText().ToString(), "partial static class StaticMapper");
        }

        [TestMethod]
        public void InvalidDeclarationsReportStableDiagnostics()
